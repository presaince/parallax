package com.presaince.glasstube.feature.player

import com.presaince.glasstube.data.model.CaptionTrackInfo
import com.presaince.glasstube.data.model.Cue
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class CaptionsTest {

    private val cues = listOf(
        Cue(startSec = 1.0, endSec = 2.5, text = " Hello there "),
        Cue(startSec = 4.0, endSec = 5.0, text = "Second line"),
    )

    @Test
    fun `before the first cue there is nothing to show`() {
        assertNull(cueAt(cues, 0))
        assertNull(cueAt(cues, 999))
    }

    @Test
    fun `a cue is shown from its start until its end, ends exclusive`() {
        assertEquals("Hello there", cueAt(cues, 1_000))
        assertEquals("Hello there", cueAt(cues, 2_499))
        // 2.5 is the end, not the last moment of the cue: lingering there shows a stale line.
        assertNull(cueAt(cues, 2_500))
    }

    @Test
    fun `a gap between cues is silent`() {
        assertNull(cueAt(cues, 3_000))
    }

    @Test
    fun `the right cue is found by a position past the middle of the list`() {
        assertEquals("Second line", cueAt(cues, 4_200))
    }

    @Test
    fun `two cues over the same moment are joined in start order`() {
        val overlapping = listOf(
            Cue(1.0, 3.0, "first"),
            Cue(1.0, 3.0, "second"),
        )
        assertEquals("first\nsecond", cueAt(overlapping, 2_000))
    }

    @Test
    fun `an empty track shows nothing rather than throwing`() {
        assertNull(cueAt(emptyList(), 5_000))
    }

    @Test
    fun `a cue whose text is only spaces shows nothing`() {
        assertNull(cueAt(listOf(Cue(1.0, 2.0, "   ")), 1_500))
    }

    @Test
    fun `the stored language wins while the video still offers it`() {
        val tracks = listOf(
            CaptionTrackInfo("en", "English", autoGenerated = true),
            CaptionTrackInfo("de", "Deutsch", autoGenerated = false),
        )
        assertEquals("de", pickCaptionTrack(tracks, "DE")?.languageTag)
    }

    @Test
    fun `a stored language the video has dropped falls back to a human track`() {
        val tracks = listOf(
            CaptionTrackInfo("en", "English", autoGenerated = true),
            CaptionTrackInfo("de", "Deutsch", autoGenerated = false),
        )
        assertEquals("de", pickCaptionTrack(tracks, "fr")?.languageTag)
    }

    @Test
    fun `a human track beats a machine one, in any language`() {
        val tracks = listOf(
            CaptionTrackInfo("de", "Deutsch", autoGenerated = false),
            CaptionTrackInfo("en", "English", autoGenerated = true),
        )
        // The extractor's own order, and the resync path's: a transcript before a guess.
        assertEquals("de", pickCaptionTrack(tracks, null)?.languageTag)
    }

    @Test
    fun `a human English track outranks a human track in another language`() {
        val tracks = listOf(
            CaptionTrackInfo("de", "Deutsch", autoGenerated = false),
            CaptionTrackInfo("en", "English", autoGenerated = false),
        )
        assertEquals("en", pickCaptionTrack(tracks, null)?.languageTag)
    }

    @Test
    fun `a video with only machine captions still offers the machine one`() {
        val tracks = listOf(CaptionTrackInfo("ja", "日本語", autoGenerated = true))
        assertEquals("ja", pickCaptionTrack(tracks, null)?.languageTag)
    }

    @Test
    fun `no tracks means no captions`() {
        assertNull(pickCaptionTrack(emptyList(), "en"))
    }

    @Test
    fun `a track tapped in the menu switches captions on`() {
        val pick = captionPick(CaptionTrackInfo("de", "Deutsch", autoGenerated = true))
        assertEquals("de", pick.languageTag)
        assertTrue("a track tap that leaves captions off is a tap that does nothing", pick.on)
    }

    @Test
    fun `off in the menu stores no language and switches captions off`() {
        val pick = captionPick(null)
        assertNull(pick.languageTag)
        assertTrue(!pick.on)
    }

    @Test
    fun `a size index outside the three steps reads as medium`() {
        assertEquals(CaptionSize.MEDIUM, CaptionSize.of(1))
        assertEquals(CaptionSize.MEDIUM, CaptionSize.of(9))
        assertEquals(CaptionSize.MEDIUM, CaptionSize.of(-2))
        assertEquals(CaptionSize.LARGE, CaptionSize.of(2))
    }
}
