package com.presaince.glasstube.data.model

/** Live and upcoming videos are listed like any other, but they cannot always be played. */
enum class StreamState { NORMAL, LIVE, UPCOMING }

data class VideoSummary(
    val id: String,
    val url: String,
    val title: String,
    val channelName: String,
    val durationSec: Long,
    val thumbnailUrl: String?,
    val channelUrl: String? = null,
    val publishedAtMs: Long? = null,
    val viewCount: Long? = null,
    val likeCount: Long? = null,
    val commentCount: Long? = null,
    val streamState: StreamState = StreamState.NORMAL,
)

/** One storyboard: a grid of video frames whose images are paged by url. */
data class PreviewFrames(
    val urls: List<String>,
    val framesPerPageX: Int,
    val framesPerPageY: Int,
    val frameWidth: Int,
    val frameHeight: Int,
    val durationPerFrameMs: Int,
    val totalCount: Int,
) {
    /**
     * The cell containing [frameMs]: which page image holds it, and where in that page's pixels.
     * This mirrors Frameset.getFrameBoundsAt, including its page arithmetic, so the crop matches
     * the extractor's own mapping.
     *
     * Null when there is nothing honest to draw: no page, a broken grid, or a frame whose page is
     * past the end of [urls]. A missing page is a reason to show the fallback picture, not to
     * stretch some other page's cell and call it the moment.
     */
    fun cellAt(frameMs: Long): StoryboardCell? {
        val perPage = framesPerPageX * framesPerPageY
        if (urls.isEmpty() || perPage <= 0 || durationPerFrameMs <= 0) return null
        if (frameWidth <= 0 || frameHeight <= 0) return null
        // A frame past the reported count is the last one, not one past the end.
        val lastFrame = if (totalCount > 0) totalCount - 1 else Int.MAX_VALUE
        val absolute = (frameMs / durationPerFrameMs).toInt().coerceIn(0, lastFrame)
        val page = absolute / perPage
        if (page > urls.lastIndex) return null
        val relative = absolute % perPage
        val row = relative / framesPerPageX
        val col = relative % framesPerPageX
        return StoryboardCell(
            page = page,
            x = col * frameWidth,
            y = row * frameHeight,
            width = frameWidth,
            height = frameHeight,
        )
    }
}

/** One storyboard cell: the page image that holds it, and its rectangle in that image's pixels. */
data class StoryboardCell(
    val page: Int,
    val x: Int,
    val y: Int,
    val width: Int,
    val height: Int,
)

data class VideoDetail(
    val id: String,
    val url: String,
    val title: String,
    val channelName: String,
    val channelUrl: String? = null,
    val durationSec: Long,
    val description: String,
    val likeCount: Long? = null,
    val previewFrames: List<PreviewFrames> = emptyList(),
)

/**
 * Stream URLs are signed and expire within hours. Never persist them: persist the video id and
 * resolve again. At most one of muxedUrl or the pair (videoUrl + audioUrl) is set.
 */
data class StreamSet(
    val muxedUrl: String? = null,
    val videoUrl: String? = null,
    val audioUrl: String? = null,
) {
    init {
        require(muxedUrl != null || (videoUrl != null && audioUrl != null)) {
            "a stream set needs a muxed URL or both a video and an audio URL"
        }
    }
}

data class Page<T>(
    val items: List<T>,
    val next: String? = null,
    val total: Long? = null,
    /** Comments only: the video's owner has switched comments off. */
    val disabled: Boolean = false,
)

data class Comment(
    val id: String,
    val author: String,
    /** The commenter's channel, when the extractor gives one. Null for a comment carved from a post. */
    val authorUrl: String? = null,
    val text: String,
    val likeCount: Int,
    val publishedText: String,
    /** The same moment as [publishedText] in millis, so comments can be sorted by age. */
    val publishedAtMs: Long? = null,
    /** The position the commenter pointed at, in seconds. Null when the extractor gave none. */
    val timestampSec: Long?,
    val pinned: Boolean,
    val replyCount: Int,
    /** Continuation token for this comment's replies, when it has any. */
    val repliesPage: String? = null,
)

data class Channel(
    val url: String,
    val name: String,
    val avatarUrl: String?,
    val subscriberCount: Long,
    /** The channel's own about text, when the extractor gives one. */
    val description: String? = null,
    /** The extractor's filter names for this channel's tabs: "videos", "shorts", "livestreams". */
    val tabs: List<String> = emptyList(),
)

/** One subtitle cue. Seconds are floats because VTT timestamps carry milliseconds. */
data class Cue(val startSec: Double, val endSec: Double, val text: String)

data class SubtitleTrack(
    val language: String,
    val autoGenerated: Boolean,
    val cues: List<Cue>,
)

/**
 * One caption track the video offers, before anything is downloaded. [languageTag] is what the
 * choice is stored as ("en", "de-AT"); [label] is what a person reads, and [autoGenerated] is the
 * difference between a transcript and a guess, so the menu can say which one it is offering.
 */
data class CaptionTrackInfo(
    val languageTag: String,
    val label: String,
    val autoGenerated: Boolean,
)
